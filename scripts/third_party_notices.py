def source_crate() -> tuple[str, Path]:
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--locked", "--format-version", "1", "--features", "ghostty-engine"], cwd=ROOT
        )
    )
    for package in metadata["packages"]:
        if package["name"] == SOURCE_CRATE:
            return package["version"], Path(package["manifest_path"]).parent
    sys.exit(f"{SOURCE_CRATE} is not in Cargo.lock")


def linked_rows(table: str) -> list[list[str]]:
    rows = []
    for line in table.splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) == 5 and cells[3] == "linked":
            rows.append(cells)
    if not rows:
        sys.exit("THIRD_PARTY.md lists no linked code; has its format changed?")
    return rows


def render() -> str:
    version, crate = source_crate()
    rows = linked_rows((crate / "THIRD_PARTY.md").read_text(encoding="utf-8"))
    out = [
        "# Third-party notices",
        "",
        "rozi is MPL-2.0 (see `LICENSE`). Builds with the experimental Ghostty terminal engine,",
        "which include the release archives, also contain the native code below, compiled from",
        f"`{SOURCE_CRATE}` {version}.",
        "",
        "Generated by `scripts/third_party_notices.py`; do not edit by hand.",
        "",
        "| Project | Version | Licence |",
        "| --- | --- | --- |",
    ]
    out += [f"| {name} | {release} | {licence} |" for name, release, licence, _, _ in rows]
    out.append("| Zig runtime (`compiler_rt`, standard library) | 0.17 | MIT |")
    for name, release, licence, _, files in rows:
        out += ["", f"## {name} {release}", "", f"Licence: {licence}."]
        for file in files.split("<br>"):
            path = file.strip().strip("`")
            text = (crate / path).read_text(encoding="utf-8").strip("\n")
            out += ["", f"`{Path(path).name}`:", "", "```text", text, "```"]
    out += ["", "## Zig runtime 0.17", "", "Licence: MIT.", "", "```text", ZIG_LICENSE.strip("\n"), "```"]
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            sys.exit(f"{OUTPUT.name} is out of date; run python3 scripts/third_party_notices.py")
        return
    OUTPUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
